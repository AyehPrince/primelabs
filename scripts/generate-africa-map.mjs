// Generates src/lib/africa-map.ts from Natural Earth data (world-atlas).
// Run once: node scripts/generate-africa-map.mjs
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { createRequire } from "node:module";
import { geoNaturalEarth1, geoPath, geoContains } from "d3-geo";
import { feature, mesh } from "topojson-client";

const require = createRequire(import.meta.url);

const RESOLUTION = "110m";
const WIDTH = 800;
const DOT_SPACING = 10; // distance between dots in map units
const OUT_FILE = "src/lib/africa-map.ts";

// ISO numeric codes for the 54 African countries recognised by the UN,
// plus Western Sahara. Somaliland has no code in the data, matched by name.
const AFRICA_IDS = new Set([
  "012", "024", "204", "072", "854", "108", "120", "132", "140", "148",
  "174", "178", "180", "384", "262", "818", "226", "232", "748", "231",
  "266", "270", "288", "324", "624", "404", "426", "430", "434", "450",
  "454", "466", "478", "480", "504", "508", "516", "562", "566", "646",
  "678", "686", "690", "694", "706", "710", "728", "729", "834", "768",
  "788", "800", "732", "894", "716",
]);

const GHANA_ID = "288";
const ACCRA_LONLAT = [-0.187, 5.603];

// Regions follow the UN geoscheme. Ghana is its own region because it is
// the home market, so it can be styled and outlined on its own.
const REGION_MEMBERS = {
  ghana: ["Ghana"],
  west: [
    "Benin", "Burkina Faso", "Côte d'Ivoire", "Gambia", "Guinea",
    "Guinea-Bissau", "Liberia", "Mali", "Mauritania", "Niger", "Nigeria",
    "Senegal", "Sierra Leone", "Togo",
  ],
  north: ["Algeria", "Egypt", "Libya", "Morocco", "Sudan", "Tunisia", "W. Sahara"],
  east: [
    "Burundi", "Djibouti", "Eritrea", "Ethiopia", "Kenya", "Madagascar",
    "Malawi", "Mozambique", "Rwanda", "Somalia", "Somaliland", "S. Sudan",
    "Tanzania", "Uganda", "Zambia", "Zimbabwe",
  ],
  central: [
    "Angola", "Cameroon", "Central African Rep.", "Chad", "Congo",
    "Dem. Rep. Congo", "Eq. Guinea", "Gabon",
  ],
  southern: ["Botswana", "eSwatini", "Lesotho", "Namibia", "South Africa"],
};

const regionByName = new Map();
for (const [region, names] of Object.entries(REGION_MEMBERS)) {
  for (const name of names) regionByName.set(name, region);
}

const topo = JSON.parse(
  readFileSync(require.resolve(`world-atlas/countries-${RESOLUTION}.json`), "utf8")
);

const all = feature(topo, topo.objects.countries).features;
const africa = all.filter(
  (f) => AFRICA_IDS.has(String(f.id).padStart(3, "0")) || f.properties.name === "Somaliland"
);

const collection = { type: "FeatureCollection", features: africa };
const projection = geoNaturalEarth1().fitWidth(WIDTH, collection);
const path = geoPath(projection).digits(1);

const [[x0, y0], [x1, y1]] = geoPath(projection).bounds(collection);
const height = Math.ceil(y1 + y0);

// Countries, each tagged with its region.
const countries = africa.map((f) => {
  const [cx, cy] = geoPath(projection).centroid(f);
  const region = regionByName.get(f.properties.name);
  if (!region) throw new Error(`No region for ${f.properties.name}`);
  return {
    id: String(f.id ?? f.properties.name).padStart(3, "0"),
    name: f.properties.name,
    region,
    d: path(f),
    cx: Math.round(cx * 10) / 10,
    cy: Math.round(cy * 10) / 10,
  };
});
const ghanaIndex = countries.findIndex((c) => c.id === GHANA_ID);
if (ghanaIndex < 0) throw new Error("Ghana not found in data");

// One path holding only the borders between two different regions.
const regionBorders = path(
  mesh(topo, topo.objects.countries, (a, b) => {
    const ra = regionByName.get(a.properties.name);
    const rb = regionByName.get(b.properties.name);
    return a !== b && ra && rb && ra !== rb;
  })
);

// Hex-packed dot grid, clipped to the continent.
const boxes = africa.map((f) => geoPath(projection).bounds(f));
const rowStep = DOT_SPACING * 0.866;
const dots = [];
let row = 0;
for (let y = y0; y <= y1; y += rowStep, row++) {
  const offset = row % 2 ? DOT_SPACING / 2 : 0;
  for (let x = x0 + offset; x <= x1; x += DOT_SPACING) {
    const lonlat = projection.invert([x, y]);
    if (!lonlat) continue;
    for (let i = 0; i < africa.length; i++) {
      const [[bx0, by0], [bx1, by1]] = boxes[i];
      if (x < bx0 || x > bx1 || y < by0 || y > by1) continue;
      if (geoContains(africa[i], lonlat)) {
        dots.push([Math.round(x * 10) / 10, Math.round(y * 10) / 10, i]);
        break;
      }
    }
  }
}

const [ax, ay] = projection(ACCRA_LONLAT);
const ghanaDots = dots.filter((d) => d[2] === ghanaIndex).length;

const out = `// GENERATED by scripts/generate-africa-map.mjs from Natural Earth data.
// Do not edit by hand. Re-run the script to regenerate.

export type RegionId =
  | "ghana"
  | "west"
  | "north"
  | "east"
  | "central"
  | "southern";

export type MapCountry = {
  id: string;
  name: string;
  region: RegionId;
  d: string;
  cx: number;
  cy: number;
};

export const MAP_WIDTH = ${WIDTH};
export const MAP_HEIGHT = ${height};
export const GHANA_INDEX = ${ghanaIndex};
export const ACCRA = { x: ${Math.round(ax * 10) / 10}, y: ${Math.round(ay * 10) / 10} } as const;

/** [x, y, countryIndex] for every dot, hex-packed. */
export const DOTS: ReadonlyArray<readonly [number, number, number]> = ${JSON.stringify(dots)};

export const COUNTRIES: ReadonlyArray<MapCountry> = ${JSON.stringify(countries)};

/** Borders drawn only where one region meets another. */
export const REGION_BORDERS = ${JSON.stringify(regionBorders)};
`;

mkdirSync("src/lib", { recursive: true });
writeFileSync(OUT_FILE, out);

const perRegion = Object.keys(REGION_MEMBERS)
  .map((r) => `${r}: ${countries.filter((c) => c.region === r).length}`)
  .join(", ");

console.log(`Countries: ${countries.length} (${perRegion})`);
console.log(`Dots: ${dots.length} (Ghana: ${ghanaDots})`);
console.log(`Map size: ${WIDTH} x ${height}`);
console.log(`Region borders: ${regionBorders ? regionBorders.length : 0} characters of path`);
console.log(`Wrote ${OUT_FILE} (${(out.length / 1024).toFixed(0)} KB)`);